//! Generated bench driver: `bench.toml` in, a driver crate out.
//!
//! The mirror of `custom_lints`: the consumer authors configuration
//! plus the code that is genuinely theirs (arm `lib.rs` files, an
//! optional hooks lib), and the tool generates everything mechanical:
//! the driver binary crate, the byte dispatch declared from the
//! manifest's own points, the workload programs declared in
//! `[workload.*]`, and a manifest for every arm directory that has
//! none.
//!
//! Where the lints analogy breaks, deliberately: routines are
//! monomorphised generics, so consumer hook code cannot live behind a
//! `dyn` cdylib boundary. The generated driver instead includes the
//! consumer's `src/lib.rs` as a `#[path]` module and calls its
//! `hooks()`, compiling it into the binary and its worker subprocess,
//! the mechanism `bench-matrix` validated (the sibling crate needs
//! the code by path, never by copy).

use std::path::{Path, PathBuf};

use mockspace_bench_harness::config::BenchManifest;
use mockspace_bench_harness::tree::{self, ArmSource, SupportSource, TreeManifest};

/// The default dependency spec for the mockspace bench crates in
/// generated manifests. Overridable per tree via `[build] mockspace`.
///
/// FIXME: not pin-matched to the running engine the way the launcher
/// passes `--mockspace-lint-rules-dep` for the lint cdylib. The
/// `bench_abi_hash` check at dlopen is a weaker guard than that pin:
/// it folds only the struct size, the field count and the field
/// widths, so a bench-core skew that reorders same-width fields (or
/// changes semantics without changing shape) passes the check and
/// misreads timing fields silently across FFI. Until the launcher's
/// pin mechanism grows a bench twin, a floating `branch = "dev"`
/// here trades that risk for zero-config; consumers who care pin a
/// rev via `[build] mockspace`, and the E2E test pins by path.
pub const DEFAULT_MOCKSPACE_DEP: &str =
    "{ git = \"https://github.com/hiisi-digital/mockspace\", branch = \"dev\" }";

/// Everything generation needs about one tree.
pub struct GenPlan {
    /// The benches root (`mock/benches/`).
    pub bench_dir:    PathBuf,
    /// The loaded manifest (root sections plus composed members).
    pub manifest:     BenchManifest,
    /// Discovered arms of composed-form members.
    pub arms:         Vec<ArmSource>,
    /// Discovered support crates.
    pub support:      Vec<SupportSource>,
    /// Sections-form members, whose `variants/` build the legacy way
    /// rooted at the member directory.
    pub flat_members: Vec<String>,
}

/// Load the tree for generation: the root manifest plus every
/// declared or defaulted benchspace member.
pub fn plan(bench_dir: &Path) -> Result<GenPlan, String> {
    let TreeManifest {
        manifest,
        arms,
        support,
        flat_members,
    } = tree::load(bench_dir).map_err(|e| e.to_string())?;
    Ok(GenPlan {
        bench_dir: bench_dir.to_path_buf(),
        manifest,
        arms,
        support,
        flat_members,
    })
}

/// The mockspace dependency spec for this tree's generated crates.
pub fn mockspace_dep(manifest: &BenchManifest) -> String {
    manifest
        .build
        .as_ref()
        .and_then(|b| b.mockspace.clone())
        .unwrap_or_else(|| DEFAULT_MOCKSPACE_DEP.to_string())
}

/// The effective monomorphisation list for the generated byte
/// dispatch: `[dispatch] points` when declared, else the union of
/// every bench's points. One source of truth; the hand-kept copy in
/// a consumer `main.rs` is what this deletes.
pub fn dispatch_points(manifest: &BenchManifest) -> Vec<usize> {
    let declared = manifest
        .dispatch
        .as_ref()
        .map(|d| d.points.clone())
        .unwrap_or_default();
    let mut points = if declared.is_empty() {
        manifest
            .bench
            .values()
            .flat_map(|s| s.sizes.iter().map(|sz| sz.n))
            .collect()
    } else {
        declared
    };
    points.sort_unstable();
    points.dedup();
    points
}

/// One parsed workload stage: a builtin constructor name and its
/// integer argument where the constructor takes one.
struct Stage {
    call: String,
}

/// Parse one stage declaration. The grammar is `name` or `name N`;
/// the names and arities are the harness's own stage constructors.
fn parse_stage(decl: &str) -> Result<Stage, String> {
    let mut parts = decl.split_whitespace();
    let name = parts.next().unwrap_or("");
    let arg = parts.next();
    if parts.next().is_some() {
        return Err(format!(
            "stage `{decl}`: at most one argument (the grammar is `name` or `name N`)"
        ));
    }
    let arity = match name {
        "algo_call" | "light_scalar" => 0,
        "scalar_work" | "graph_work" | "branch_work" | "heavy_memory" => 1,
        other => {
            return Err(format!(
                "unknown stage `{other}`. The builtins are: algo_call, light_scalar, \
                 scalar_work N, graph_work N, branch_work N, heavy_memory N"
            ));
        },
    };
    match (arity, arg) {
        (0, None) => Ok(Stage {
            call: format!("harness::{name}()"),
        }),
        (1, Some(v)) => {
            let v: u64 = v
                .parse()
                .map_err(|_| format!("stage `{decl}`: `{v}` is not an integer"))?;
            Ok(Stage {
                call: format!("harness::{name}({v})"),
            })
        },
        (0, Some(v)) => Err(format!("stage `{decl}`: `{name}` takes no argument, got `{v}`")),
        (1, None) => Err(format!("stage `{decl}`: `{name}` needs an integer argument")),
        _ => unreachable!(),
    }
}

/// The two builtin workload programs. `realistic` is the six-stage
/// mix two consumers independently copied; `default` is the light
/// starter mix. A `[workload.<name>]` declaration of either name
/// overrides the builtin.
const BUILTIN_WORKLOADS: &[(&str, &[&str])] = &[
    ("default", &["algo_call", "light_scalar"]),
    ("realistic", &[
        "algo_call",
        "scalar_work 48",
        "graph_work 32",
        "heavy_memory 384",
        "branch_work 24",
        "light_scalar",
    ]),
];

/// Generate the `build_workload` function from the manifest's
/// `[workload.*]` declarations plus the builtins, refusing unknown
/// stages and any bench whose `workload` names a program that is
/// neither declared nor builtin.
pub fn workload_fn_source(manifest: &BenchManifest) -> Result<String, String> {
    // declared programs override builtins of the same name
    let mut programs: Vec<(String, Vec<String>)> = Vec::new();
    for (name, stages) in BUILTIN_WORKLOADS {
        if !manifest.workload.contains_key(*name) {
            programs.push((
                name.to_string(),
                stages.iter().map(|s| s.to_string()).collect(),
            ));
        }
    }
    let mut declared: Vec<(&String, &mockspace_bench_harness::config::WorkloadSection)> =
        manifest.workload.iter().collect();
    // Sort by borrowed key rather than cloning: `name` is a `&&String` here,
    // so `.clone()` duplicated the reference rather than the string and the
    // allocation it looked like it was avoiding never happened either way.
    declared.sort_by(|a, b| a.0.cmp(b.0));
    for (name, section) in declared {
        programs.push((name.clone(), section.stages.clone()));
    }
    programs.sort_by(|a, b| a.0.cmp(&b.0));

    // every bench's workload must resolve
    for (bench, section) in &manifest.bench {
        if !programs.iter().any(|(n, _)| n == &section.workload) {
            let known: Vec<&str> = programs.iter().map(|(n, _)| n.as_str()).collect();
            return Err(format!(
                "bench `{bench}` uses workload `{}`, which is neither declared in \
                 [workload.*] nor a builtin. Known programs: {}",
                section.workload,
                known.join(", ")
            ));
        }
    }

    let mut arms_src = String::new();
    for (name, stages) in &programs {
        let calls: Vec<String> = stages
            .iter()
            .map(|s| parse_stage(s).map(|st| st.call))
            .collect::<Result<_, _>>()
            .map_err(|e| format!("workload `{name}`: {e}"))?;
        arms_src.push_str(&format!(
            "        {name:?} => {{\n            w.program({name:?}, |b| {{\n                \
             b.stage(vec![{}]);\n            }});\n        }},\n",
            calls.join(", ")
        ));
    }
    Ok(format!(
        "fn build_workload(name: &str, _n: usize) -> Workload {{\n    let mut w = \
         Workload::new();\n    match name {{\n{arms_src}        other => panic!(\n            \
         \"workload `{{other}}` reached the driver ungenerated; the generation step \\\n             \
             validates every bench's workload, so this is a generator defect\"\n        ),\n    \
         }}\n    w\n}}\n"
    ))
}

/// Generate the driver crate's `main.rs`.
pub fn driver_main_source(manifest: &BenchManifest, hooks_lib: Option<&Path>) -> Result<String, String> {
    let out = manifest.dispatch.as_ref().map(|d| d.out).unwrap_or(8);
    let points = dispatch_points(manifest);
    if points.is_empty() {
        return Err("no bench declares any points, so there is nothing to generate".into());
    }
    let points_list = points
        .iter()
        .map(|p| p.to_string())
        .collect::<Vec<_>>()
        .join(", ");
    let workload_fn = workload_fn_source(manifest)?;
    let hooks_src = match hooks_lib {
        Some(lib) => {
            format!(
                "#[path = {:?}]\nmod consumer_hooks;\n\nfn hooks() -> Hooks {{\n    \
                 consumer_hooks::hooks()\n}}\n",
                lib.display().to_string()
            )
        },
        None => "fn hooks() -> Hooks {\n    Hooks::default()\n}\n".to_string(),
    };
    Ok(format!(
        "//! GENERATED by `mock bench` from bench.toml. Do not edit; the\n//! consumer-owned \
         parts live in bench.toml, the arm crates, and the\n//! optional src/lib.rs hooks \
         library.\n\nuse std::process::ExitCode;\n\nuse mockspace_bench_core::byte_routine_dispatch;\n\
         use mockspace_bench_harness::driver::{{drive_spec, DriverSpec, Hooks}};\n\
         use mockspace_bench_harness::{{self as harness, Workload}};\n\n{hooks_src}\n{workload_fn}\n\
         fn main() -> ExitCode {{\n    drive_spec(&DriverSpec {{\n        build_workload,\n        \
         byte_dispatch: byte_routine_dispatch!(out = {out}, sizes = [{points_list}]),\n        \
         hooks: hooks(),\n    }})\n}}\n"
    ))
}

/// Generate the driver crate's `Cargo.toml`. Support crates become
/// path dependencies so a hooks library can `use` them.
pub fn driver_cargo_toml(dep: &str, support: &[SupportSource]) -> Result<String, String> {
    let mut manifest = format!(
        "# GENERATED by `mock bench`. Do not edit.\n[workspace]\n\n[package]\nname = \
         \"mockspace-bench-driver\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [[bin]]\nname = \"mockspace-bench-driver\"\npath = \"src/main.rs\"\n\n[dependencies]\n\
         mockspace-bench-core = {}\nmockspace-bench-harness = {}\n",
        with_feature(&dep_for_crate(dep, "bench-core"), "std"),
        dep_for_crate(dep, "bench-harness"),
    );
    for s in support {
        let name = support_package_name(s)?;
        manifest.push_str(&format!(
            "{name} = {{ path = {:?} }}\n",
            s.dir.display().to_string()
        ));
    }
    Ok(manifest)
}

/// Generate the manifest for an arm directory that has none: the
/// `[workspace]` header (so an outer workspace cannot capture it),
/// the cdylib crate type, the pinned framework deps, and this
/// bench's support crates.
pub fn arm_cargo_toml(
    arm: &ArmSource,
    dep: &str,
    support: &[SupportSource],
) -> Result<String, String> {
    let lib_name = arm.arm.replace('-', "_");
    let mut manifest = format!(
        "# GENERATED by `mock bench` for {}/arms/{}. Do not edit; write a\n\
         # Cargo.toml in the arm directory to take the manifest over.\n\
         [workspace]\n\n[package]\nname = \"{lib_name}\"\nversion = \"0.0.0\"\nedition = \
         \"2021\"\npublish = false\n\n[lib]\nname = \"{lib_name}\"\npath = {:?}\ncrate-type = \
         [\"cdylib\"]\n\n[dependencies]\nmockspace-bench-core = {}\nmockspace-bench-macro = {}\n",
        arm.bench,
        arm.arm,
        arm.dir.join("src/lib.rs").display().to_string(),
        with_feature(&dep_for_crate(dep, "bench-core"), "std"),
        dep_for_crate(dep, "bench-macro"),
    );
    for s in support
        .iter()
        .filter(|s| s.bench.is_none() || s.bench.as_deref() == Some(arm.bench.as_str()))
    {
        let name = support_package_name(s)?;
        manifest.push_str(&format!(
            "{name} = {{ path = {:?} }}\n",
            s.dir.display().to_string()
        ));
    }
    Ok(manifest)
}

/// A support crate's package name, from its own manifest. A support
/// crate without a manifest is refused: it is an ordinary library
/// crate the consumer owns, not something the tool scaffolds.
pub fn support_package_name(s: &SupportSource) -> Result<String, String> {
    let manifest_path = s.dir.join("Cargo.toml");
    let text = std::fs::read_to_string(&manifest_path).map_err(|_| {
        format!(
            "support crate {} has no Cargo.toml. Support crates are ordinary library \
             crates; give it a manifest (only arm manifests are generated).",
            s.dir.display()
        )
    })?;
    let doc: toml_edit::DocumentMut = text
        .parse()
        .map_err(|e| format!("{}: {e}", manifest_path.display()))?;
    let is_cdylib = doc
        .get("lib")
        .and_then(|l| l.get("crate-type"))
        .and_then(|c| c.as_array())
        .is_some_and(|arr| arr.iter().any(|v| v.as_str() == Some("cdylib")));
    if is_cdylib {
        return Err(format!(
            "support crate {} declares `crate-type = [\"cdylib\"]`. A support crate \
             is a library the arms and the driver link and is never measured; a \
             measured cdylib belongs under arms/, not support/.",
            s.dir.display()
        ));
    }
    doc.get("package")
        .and_then(|p| p.get("name"))
        .and_then(|n| n.as_str())
        .map(str::to_string)
        .ok_or_else(|| format!("{} has no [package] name", manifest_path.display()))
}

/// The dependency spec for one mockspace bench crate.
///
/// A git spec applies verbatim: cargo resolves the crate by name
/// inside the repository. A path spec names the mockspace repository
/// root and expands per crate (`{ path = "/x" }` becomes
/// `{ path = "/x/bench-core" }`), which is what local development
/// and in-repo tests need, since one path cannot serve three crates.
pub fn dep_for_crate(dep: &str, crate_subdir: &str) -> String {
    if let Some(root) = extract_between(dep, "path = \"", "\"") {
        let joined = Path::new(&root).join(crate_subdir);
        format!("{{ path = {:?} }}", joined.display().to_string())
    } else {
        dep.to_string()
    }
}

/// The value between `open` and the next `close` in `s`.
fn extract_between(s: &str, open: &str, close: &str) -> Option<String> {
    let start = s.find(open)? + open.len();
    let end = s[start ..].find(close)? + start;
    Some(s[start .. end].to_string())
}

/// Append a feature list to a dependency spec written as an inline
/// table string.
fn with_feature(dep: &str, feature: &str) -> String {
    match dep.trim_end().strip_suffix('}') {
        Some(head) => format!("{head}, features = [{feature:?}] }}"),
        None => dep.to_string(),
    }
}

/// Write a generated file only when its content changed, so cargo's
/// freshness check skips rebuilds when nothing moved.
pub fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("creating {}: {e}", parent.display()))?;
    }
    if std::fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    std::fs::write(path, content).map_err(|e| format!("writing {}: {e}", path.display()))
}

/// Where the generated driver crate lives: under the mock target
/// tree, like the generated lint crate, never in the consumer's
/// source tree.
pub fn driver_gen_dir(mock_dir: &Path) -> PathBuf {
    mock_dir.join("target").join("mockspace-bench")
}

/// Where a generated arm manifest lives (the crate points back at
/// the consumer's `src/lib.rs` by path).
pub fn arm_gen_dir(mock_dir: &Path, arm: &ArmSource) -> PathBuf {
    mock_dir
        .join("target")
        .join("mockspace-bench-arms")
        .join(&arm.bench)
        .join(&arm.arm)
}

